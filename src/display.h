 // ================= TEXT DRAWING =================
 
 static void draw_char(int x, int y, char c,
                uint16_t color, int scale) {
 
     unsigned char ch = (unsigned char)c;
 
     if (ch < 32 || ch > 126) {
         ch = '?';
     }
 
     int index = ch - 32;
 
     for (int col = 0; col < 5; col++) {
         uint8_t column = font5x7[index][col];
 
         for (int row = 0; row < 7; row++) {
             if (column & (1u << row)) {
                 lcd_rect(
                     x + col * scale,
                     y + row * scale,
                     scale,
                     scale,
                     color
                 );
             }
         }
     }
 }
 
 static void draw_text(int x, int y,
                const char *text,
                uint16_t color, int scale) {
 
     int start_x = x;
 
     while (*text) {
 
         if (*text == '\n') {
             x = start_x;
             y += 9 * scale;
         }
         else {
             draw_char(x, y, *text, color, scale);
             x += 6 * scale;
         }
 
         text++;
     }
 }

